// Compiles src/bridge/pageClient.ts into src/bridge/pageClient.generated.ts: the page client as one function
// expression in a string, so native can inject `(<PAGE_CLIENT>)(window, <timeoutMs>)` at document start.
// Run after editing pageClient.ts: node internal/build-page-client.mjs (`--check` fails if the output is stale).
import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

const source = new URL('../src/bridge/pageClient.ts', import.meta.url);
const target = new URL('../src/bridge/pageClient.generated.ts', import.meta.url);

const { outputText } = ts.transpileModule(readFileSync(source, 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: true },
});
const fn = outputText.replace(/^export /m, '').trim();
if (!fn.startsWith('function installPageClient(')) throw new Error('pageClient.ts must only export installPageClient');
const output = `// Generated by internal/build-page-client.mjs from pageClient.ts. Do not edit.\nexport const PAGE_CLIENT = ${JSON.stringify(fn)};\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('pageClient.generated.ts is stale: run node internal/build-page-client.mjs');
} else {
  writeFileSync(target, output);
}
